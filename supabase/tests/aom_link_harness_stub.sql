-- LOCAL SCRATCH-DB ONLY (atomic_aom_link_test on a throwaway local Postgres). Minimal stand-ins for the
-- Supabase platform bits the EOS schema files need. Never run against a Supabase project.
drop schema if exists public cascade;
drop schema if exists auth cascade;
drop schema if exists storage cascade;
create schema public;
do $$ declare r text; begin
  foreach r in array array['anon','authenticated','service_role'] loop
    if not exists (select 1 from pg_roles where rolname = r) then execute format('create role %I nologin', r); end if;
  end loop;
end $$;
alter role service_role bypassrls; -- as on Supabase
grant usage on schema public to anon, authenticated, service_role;
alter default privileges in schema public grant all on tables to anon, authenticated, service_role;
alter default privileges in schema public grant all on sequences to anon, authenticated, service_role;
create schema if not exists extensions;
create extension if not exists citext with schema extensions;
create schema auth;
grant usage on schema auth to anon, authenticated, service_role;
create function auth.uid() returns uuid language sql stable
  as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create function auth.role() returns text language sql stable
  as $$ select nullif(current_setting('request.jwt.claim.role', true), '') $$;
grant execute on function auth.uid(), auth.role() to anon, authenticated, service_role;
create schema storage;
create table storage.buckets (id text primary key, name text, public boolean, file_size_limit bigint);
create table storage.objects (bucket_id text, name text, owner uuid);
alter table storage.objects enable row level security;
create table public.companies (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  name text not null
);
create table public.sales (
  id bigint generated by default as identity primary key,
  first_name text not null default 'Pending', last_name text not null default 'Pending',
  email extensions.citext not null, administrator boolean not null, user_id uuid not null,
  disabled boolean not null default false
);
-- verbatim from supabase/schemas/02_functions.sql
CREATE OR REPLACE FUNCTION "public"."is_admin"() RETURNS boolean
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
begin
  return exists (
    select 1 from public.sales where user_id = auth.uid() and administrator = true
  );
end;
$$;
create table public.deals (id bigint generated by default as identity primary key);
